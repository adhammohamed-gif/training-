"""Build every training page from one template.

Usage (from the repository root):  python3 tools/build_pages.py

Reads tools/trainings.json and writes <path>/index.html for each training.
To add a training: add an entry to trainings.json, write its content file in
content/, add it to CONTENT in api/ask.js, then run this script.
"""
import html
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

TEMPLATE = """<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{title}</title>
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link href="https://fonts.googleapis.com/css2?family=IBM+Plex+Mono:wght@400;500&family=IBM+Plex+Sans:wght@400;500;600&family=Source+Serif+4:opsz,wght@8..60,600;8..60,700&display=swap" rel="stylesheet">
<link rel="stylesheet" href="{up}assets/styles.css">
</head>
<body>
<!-- Generated by tools/build_pages.py from tools/trainings.json. Edit those, not this file. -->
<div class="app">
  <aside class="rail" id="rail" aria-label="Training modules">
    <div class="rail-head">
      <a class="homelink" href="{up}">← All trainings</a>
      <div class="brand">{brand}<small>{brandSmall}</small></div>
      <div class="meter">
        <div class="meter-row"><span>Content explored</span><span id="pctTxt">0%</span></div>
        <div class="bar"><span id="pctBar"></span></div>
        <div class="meter-row"><span>Quick-check score</span><span id="scoreTxt">0 / 0</span></div>
      </div>
    </div>
    <nav class="nav" id="nav"></nav>
    <div class="rail-foot">
      <span>{footer}</span>
      <button class="linkbtn" id="resetBtn" type="button">Reset my progress</button>
    </div>
  </aside>

  <main class="main">
    <div class="topbar">
      <button class="btn" id="menuBtn" type="button" aria-controls="rail" aria-expanded="false">Modules</button>
      <strong>{topTitle}</strong>
      <a class="homelink" href="{up}">Home</a>
    </div>
    <div class="log" id="log" aria-live="polite"><div class="thread" id="thread"></div></div>
    <div class="composer">
      <form id="ask">
        <label for="q" style="position:absolute;left:-9999px">Ask a question</label>
        <input id="q" type="text" autocomplete="off" placeholder="{placeholder}">
        <button class="send" type="submit">Ask</button>
      </form>
      <div class="hint">Typed questions are answered by AI using only this training's content, with links to the sections used. Or click a chip to follow the guided path.</div>
    </div>
  </main>
</div>
<span id="topPct" hidden>0%</span>

<script>window.TRAINING = {config};</script>
{scripts}
<script src="{up}assets/app.js"></script>
</body>
</html>
"""


def build():
    with open(os.path.join(ROOT, "tools", "trainings.json"), encoding="utf-8") as f:
        trainings = json.load(f)
    for t in trainings:
        depth = len(t["path"].strip("/").split("/"))
        up = "../" * depth
        config = {k: t[k] for k in ("id", "storageKey", "welcomeTitle", "welcomeText", "avatar")}
        page = TEMPLATE.format(
            title=html.escape(t["title"]),
            brand=html.escape(t["brand"]),
            brandSmall=html.escape(t["brandSmall"]),
            topTitle=html.escape(t["topTitle"]),
            footer=html.escape(t["footer"]),
            placeholder=html.escape(t["placeholder"]),
            up=up,
            config=json.dumps(config, ensure_ascii=False).replace("</", "<\\/"),
            scripts="\n".join(f'<script src="{up}{s}"></script>' for s in t["scripts"]),
        )
        out_dir = os.path.join(ROOT, t["path"])
        os.makedirs(out_dir, exist_ok=True)
        with open(os.path.join(out_dir, "index.html"), "w", encoding="utf-8") as f:
            f.write(page)
        print("wrote", os.path.join(t["path"], "index.html"))


if __name__ == "__main__":
    build()
